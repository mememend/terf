export function profileText(profile: {
  name: string;
  level: number;
  balance: number;
  numbers: number;
  portfolio: number;
}): string {
  return (
    `<b>${profile.name}</b>\n\n` +
    `Уровень: ${profile.level}\n` +
    `Баланс: ${formatMoney(profile.balance)} ₽\n` +
    `Номеров: ${profile.numbers}\n` +
    `Стоимость коллекции: ${formatMoney(profile.portfolio)} ₽`
  );
}

function formatMoney(value: number): string {
  return new Intl.NumberFormat('ru-RU').format(Math.round(value));
}
